def generate_scr_narrative(findings: dict) -> dict:

    # --------------------------------------------------------
    # Get Gemini API key from Colab Secrets
    # --------------------------------------------------------

    try:
        key = userdata.get("gemini_api")
    except Exception:
        key = None

    # --------------------------------------------------------
    # TASK 4:
    # If no API key is configured, use offline fallback.
    # --------------------------------------------------------

    if not key:
        print("No Gemini API key found. Using offline fallback.")
        return generate_scr_narrative_offline(findings)

    # Create Gemini client
    client = genai.Client(api_key=key)

    # --------------------------------------------------------
    # Convert month dynamically
    # --------------------------------------------------------

    true_peak_month = format_month(
        findings["true_peak_month"]["month"]
    )

    outlier_month = format_month(
        findings["outlier_inflated_month"]["month"]
    )

    # --------------------------------------------------------
    # System instruction
    # --------------------------------------------------------

    system_instruction = """
You are a senior data analyst writing for Mamaearth's regional ops and
finance heads.

Write the business narrative using exactly three labeled sections:

Situation
Complication
Resolution

Requirements:
- Every number in the output must come from the supplied findings.
- Every number must appear with the same value as provided in the findings.
- Do not invent, estimate, calculate, or derive any new statistics.
- Do not introduce numerical facts that are not present in the findings.
- Use only the information provided in the findings.
- Keep the narrative professional, concise, and business-focused.
- Clearly explain the business meaning of the verified findings.
- The output must contain exactly the three sections:
  Situation, Complication, Resolution.
- When reporting a month stored as YYYY-MM, write it using the
  human-readable month name and year, such as "March 2026".
- The verified peak month and its revenue must be stated together.
"""

    # --------------------------------------------------------
    # Build the user prompt dynamically from findings
    # --------------------------------------------------------

    user_prompt = f"""
Write an SCR business narrative using the following verified findings.

Cleaned total revenue:
₹{findings['cleaned_total_revenue_inr']:.2f}

Raw total revenue:
₹{findings['raw_total_revenue_inr']:.2f}

Duplicate reconciliation delta:
₹{findings['duplicate_reconciliation_delta_inr']:.2f}

Return rate by payment method:
COD: {findings['return_rate_by_payment']['COD']:.1f}%
CARD: {findings['return_rate_by_payment']['CARD']:.1f}%
UPI: {findings['return_rate_by_payment']['UPI']:.1f}%

Highest-risk segment:
Payment method: {findings['highest_risk_segment']['payment_method']}
City tier: {findings['highest_risk_segment']['city_tier']}
Return rate: {findings['highest_risk_segment']['return_rate_pct']:.1f}%

True peak month:
Month: {true_peak_month}
Revenue: ₹{findings['true_peak_month']['revenue_inr']:.2f}

Outlier-inflated month:
Month: {outlier_month}
Apparent revenue: ₹{findings['outlier_inflated_month']['apparent_revenue_inr']:.2f}
Corrected revenue: ₹{findings['outlier_inflated_month']['corrected_revenue_inr']:.2f}

Important:
- Use the month name and year for the true peak month.
- State the true peak month and its revenue together.
- Do not change or round any supplied numerical value.
- Do not add any statistics that are not supplied.

Use exactly these three sections:

Situation

Complication

Resolution
"""

    # ========================================================
    # TASK 3 - Parameter locking and error handling
    # ========================================================

    try:

        # Temperature is 0.0 because this is a factual business
        # report, not creative writing. We want deterministic output.

        response = client.models.generate_content(
            model="gemini-3.5-flash-lite",
            contents=user_prompt,
            config=types.GenerateContentConfig(
                system_instruction=system_instruction,

                # Deterministic output
                temperature=0.0,

                # Explicitly above the required minimum
                max_output_tokens=300,

                # Timeout is 30 seconds = 30000 milliseconds.
                # This is above the required 10-second minimum.
                http_options=types.HttpOptions(
                    timeout=30000
                )
            )
        )

        # Get token usage if available
        tokens = None

        if response.usage_metadata is not None:
            tokens = response.usage_metadata.total_token_count

        # Return structured success response
        return {
            "status": "success",
            "narrative": response.text,
            "tokens": tokens
        }

    except Exception as err:

        # Never allow the caller to receive a raw exception.
        # Return a structured error response instead.

        return {
            "status": "error",
            "narrative": None,
            "message": str(err)
        }


