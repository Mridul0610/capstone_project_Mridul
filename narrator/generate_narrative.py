def format_month(month_value: str) -> str:
    """
    Convert YYYY-MM format into a human-readable month.

    Example:
    2026-03 -> March 2026
    """

    try:
        return datetime.strptime(
            month_value,
            "%Y-%m"
        ).strftime("%B %Y")

    except ValueError:
        # If the value is already in another format,
        # return it unchanged.
        return month_value


