def generate_scr_narrative_offline(findings: dict) -> dict:
    """
    Fully deterministic offline fallback.

    This function:
    - Does not use Gemini
    - Does not use an API key
    - Does not make a network call
    - Uses only values from findings
    """

    # Convert months dynamically
    true_peak_month = format_month(
        findings["true_peak_month"]["month"]
    )

    outlier_month = format_month(
        findings["outlier_inflated_month"]["month"]
    )

    narrative = f"""
Situation

Mamaearth's cleaned total revenue is ₹{findings['cleaned_total_revenue_inr']:.2f},
compared with the raw total revenue of ₹{findings['raw_total_revenue_inr']:.2f}.
The duplicate reconciliation delta is ₹{findings['duplicate_reconciliation_delta_inr']:.2f}.
Return rates vary by payment method: COD is
{findings['return_rate_by_payment']['COD']:.1f}%,
CARD is {findings['return_rate_by_payment']['CARD']:.1f}%, and
UPI is {findings['return_rate_by_payment']['UPI']:.1f}%.

Complication

The highest-risk segment is
{findings['highest_risk_segment']['payment_method']}
in city tier {findings['highest_risk_segment']['city_tier']},
with a {findings['highest_risk_segment']['return_rate_pct']:.1f}% return rate.

The apparent peak in {outlier_month} is
₹{findings['outlier_inflated_month']['apparent_revenue_inr']:.2f},
but after accounting for outliers its corrected revenue is
₹{findings['outlier_inflated_month']['corrected_revenue_inr']:.2f}.

Resolution

The verified revenue peak is {true_peak_month} at
₹{findings['true_peak_month']['revenue_inr']:.2f}.

Regional operations and finance teams should use the cleaned revenue figures,
focus return investigation on the identified high-risk payment and city-tier
segment, and use the outlier-corrected monthly trend for business decisions.
"""

    return {
        "status": "success",
        "narrative": narrative.strip(),
        "tokens": None
    }


