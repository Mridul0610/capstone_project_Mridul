def check_numeric_accuracy(narrative: str) -> bool:
    """
    Checks whether all five required figures are present
    in the narrative.

    Commas are removed before checking so that:
    97,358.30 and 97358.30 are treated as equivalent.
    """

    # Normalize commas and convert to lowercase
    normalized = narrative.replace(",", "").lower()

    # Required figures
    checks = [
        (
            "Cleaned total revenue",
            "97358.30"
        ),
        (
            "COD return rate",
            "44.4"
        ),
        (
            "COD + Tier-2 return rate",
            "54.5"
        ),
        (
            "Duplicate reconciliation delta",
            "2501.90"
        )
    ]

    all_passed = True

    # --------------------------------------------------------
    # Check first four figures using assert
    # --------------------------------------------------------

    for label, figure in checks:

        try:
            assert figure in normalized

            print(
                f"PASS - {label}: {figure}"
            )

        except AssertionError:

            print(
                f"FAIL - {label}: {figure}"
            )

            all_passed = False

    # --------------------------------------------------------
    # Check March + 20318.90 using assert
    # --------------------------------------------------------

    try:

        assert "march" in normalized

        assert (
            "20318.90" in normalized
            or "20318.9" in normalized
        )

        print(
            "PASS - True peak month: March + 20318.90"
        )

    except AssertionError:

        print(
            "FAIL - True peak month: March + 20318.90"
        )

        all_passed = False

    # --------------------------------------------------------
    # Final result
    # --------------------------------------------------------

    if all_passed:

        print("\nTASK 5: PASS")

    else:

        print("\nTASK 5: FAIL")

    return all_passed


